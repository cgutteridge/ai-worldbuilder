def pct(t: int, n: int) -> str:
    """Percentage text that never rounds up to 100% unless every column counts.

    @param t: part
    @param n: whole
    @returns: e.g. '100%', '99.6%', '0%'
    """
    if n and t == n:
        return '100%'
    if not t:
        return '0%'
    return f'{min(99.9, 100 * t / n):.1f}%'


def parcel_state(n: int, t: int, signed: bool) -> str:
    """Coverage state of one parcel (no sign-off gate — ticket #31).

    @param n: columns in the parcel
    @param t: touched columns
    @param signed: ignored (sign-offs removed)
    @returns: 'done' at 100% touched; else 'touched' (t > 0) or 'untouched'
    """
    del signed
    if n and t == n:
        return 'done'
    return 'touched' if t else 'untouched'


def stats(area: Area, touched: set, signoffs: dict) -> dict:
    """Per-parcel coverage numbers.

    @param area: Area
    @param touched: touched columns
    @param signoffs: load_signoffs()
    @returns: {parcel id: {'n', 't', 'pct', 'state', 'signed', 'lapsed', 'moved'}}
    """
    out = {}
    for pid, p in area.parcels.items():
        n = p['n']
        t = sum(1 for c in p['set'] if c in touched)
        s = signoffs.get(pid)
        out[pid] = {'n': n, 't': t, 'pct': 100.0 * t / n, 'state': parcel_state(n, t, bool(s)),
                    'signed': bool(s), 'lapsed': bool(s) and t < n,
                    'moved': bool(s) and s.get('digest') not in (None, p['digest'])}
    return out



def focus_cell() -> tuple[int, int]:
    """Focus cell from the registry marker, else world-frame origin (ticket #31).

    @returns: (tx, tz)
    """
    from cell_registry import view_registry
    cur = view_registry().marker_cell()
    if cur is not None:
        return cur
    try:
        from cellmath import origin_cell
        return origin_cell()
    except Exception:
        pass
    if COVERAGE_TXT.exists():
        m = re.search(
            r'Origin cell for current focus:\s*tx=(-?\d+)\s+tz=(-?\d+)',
            COVERAGE_TXT.read_text(),
        )
        if m:
            return int(m.group(1)), int(m.group(2))
    raise SystemExit('no registry marker, origin cell, or COVERAGE.txt focus line')


def cell_rollup(areas: list, touched: set, signoffs: dict) -> list:
    """Per-128-cell totals; ring distance uses registry focus (ticket #31).

    Prefer registry DONE when a cell is registered; otherwise parcel touch stats.

    @param areas: [Area, ...]
    @param touched: touched columns
    @param signoffs: load_signoffs() (empty under #31)
    @returns: [{'cell', 'area', 'r', 'cols', 'touched', 'done', 'parcels': Counter(state),
               'gaps', 'open_gaps', 'status'}, ...] sorted by ring, then cell
    """
    fx, fz = focus_cell()
    seen, rows = set(), []
    holds = load_holds()
    from cell_registry import view_registry
    reg_done = {c for c, v in view_registry().view().items() if v.done}
    for a in areas:
        st = stats(a, touched, signoffs)
        own = a.owner()
        for tx, tz in a.core_cells():
            if (tx, tz) in seen:
                continue
            seen.add((tx, tz))
            x0, z0, x1, z1 = cell_bbox(tx, tz, tx, tz)
            cols = t = d = 0
            pids = set()
            for x in range(x0, x1 + 1):
                for z in range(z0, z1 + 1):
                    pid = own[(x, z)]
                    pids.add(pid)
                    cols += 1
                    t += (x, z) in touched
                    d += st[pid]['state'] == 'done'
            states = Counter(st[p]['state'] for p in pids)
            gaps = [p for p in pids if a.parcels[p]['kind'] in GAPLIKE]
            if (tx, tz) in reg_done:
                status = 'done'
            else:
                status = 'done' if d == cols else 'partial' if t else 'untouched'
            if holds.get((tx, tz)):
                status = 'held'
            rows.append({'cell': (tx, tz), 'area': a.name, 'r': max(abs(tx - fx), abs(tz - fz)),
                         'cols': cols, 'touched': t, 'done': d, 'parcels': states, 'n_parcels': len(pids),
                         'gaps': len(gaps), 'open_gaps': sum(st[p]['state'] != 'done' for p in gaps),
                         'status': status})
    return sorted(rows, key=lambda r: (r['r'], r['cell']))


def registry_rollup_rows() -> list[dict]:
    """Per-cell status from the cell registry alone (ticket #33).

    @returns: [{'cell', 'r', 'status', 'left', 'ground', 'trees', 'decor', 'hold'}, ...]
              sorted by ring then cell; empty when the registry is empty
    """
    from cell_registry import view_registry

    try:
        fx, fz = focus_cell()
    except SystemExit:
        fx, fz = 0, 0
    rows = []
    for (tx, tz), v in view_registry().view().items():
        if v.done:
            status = 'done'
        elif v.hold:
            status = 'held'
        elif v.ground != 'none' or v.trees or v.decor:
            status = 'partial'
        else:
            status = 'registered'
        rows.append({
            'cell': (tx, tz),
            'r': max(abs(tx - fx), abs(tz - fz)),
            'status': status,
            'left': list(v.left),
            'ground': v.ground,
            'trees': v.trees,
            'decor': v.decor,
            'hold': v.hold,
            'marker': 'up' if v.marker else 'none',
        })
    return sorted(rows, key=lambda r: (r['r'], r['cell']))


def registry_rollup_text(rows: list[dict] | None = None) -> str:
    """Render registry cells for the COVERAGE.txt generated block.

    @param rows: from :func:`registry_rollup_rows` (default: compute)
    @returns: text lines (no markers)
    """
    rows = rows if rows is not None else registry_rollup_rows()
    lines = [
        f'registry rollup {datetime.now().strftime("%Y-%m-%d %H:%M")} '
        f'({len(rows)} cell(s); source = registry/journal.jsonl)',
        'tx,tz  |  r  |  status  |  ground  |  trees  |  decor  |  marker  |  left',
    ]
    if not rows:
        lines.append('(registry empty)')
        return '\n'.join(lines)
    for r in rows:
        tx, tz = r['cell']
        left = ', '.join(r['left']) if r['left'] else '—'
        hold = f' hold={r["hold"]}' if r.get('hold') else ''
        lines.append(
            f'{tx},{tz}  |  r={r["r"]}  |  status={r["status"]}{hold}  |  '
            f'ground={r["ground"]}  |  trees={"yes" if r["trees"] else "no"}  |  '
            f'decor={"yes" if r["decor"] else "no"}  |  marker={r["marker"]}  |  {left}'
        )
    return '\n'.join(lines)


def rollup_text(rows: list, n_builds: int) -> str:
    """Render cell_rollup rows as the generated PROCESSED CELLS block.

    @param rows: cell_rollup output
    @param n_builds: number of builds counted as touched
    @returns: text between the BEGIN / END markers (no markers)
    """
    lines = [f'generated {datetime.now().strftime("%Y-%m-%d %H:%M")} from {n_builds} builds '
             f'(reverted excluded); done = 100% columns touched or registry DONE',
             'tx,tz  |  r  |  area  |  status  |  columns done / touched  |  '
             'parcels done/touched/untouched  |  gaps open/all']
    for r in rows:
        tx, tz = r['cell']
        p = r['parcels']
        lines.append(
            f'{tx},{tz}  |  r={r["r"]}  |  {r["area"]}  |  status={r["status"]}  |  '
            f'cols {r["cols"]}: done {pct(r["done"], r["cols"])}  touched {pct(r["touched"], r["cols"])}  |  '
            f'parcels {r["n_parcels"]}: {p["done"]}/{p["touched"]}/{p["untouched"]}  |  '
            f'gaps {r["open_gaps"]}/{r["gaps"]}')
    return '\n'.join(lines)


def replace_section(text: str, body: str) -> str:
    """Swap the text between the BEGIN / END markers.

    @param text: whole COVERAGE.txt
    @param body: new generated block
    @returns: updated text
    @raises ValueError: if the markers are missing or out of order
    """
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise ValueError('COVERAGE.txt: generated markers missing or out of order')
    return text[:i + len(BEGIN)] + '\n' + body + '\n' + text[j:]


def write_coverage(areas: list | None = None, by_build: dict | None = None) -> str:
    """Regenerate the PROCESSED CELLS block of site/COVERAGE.txt.

    Always includes a registry rollup (ticket #33). Parcel/area tables are appended
    when coverage areas have been built.

    @param areas: [Area, ...] (default: load all built areas; empty list skips parcels)
    @param by_build: touched_by_build() (default: compute when areas present)
    @returns: the generated block
    """
    parts = [registry_rollup_text()]
    try:
        areas = areas if areas is not None else load_areas(built_only=True)
    except SystemExit:
        areas = []
    if areas:
        by_build = by_build if by_build is not None else touched_by_build()
        parts.append('')
        parts.append(rollup_text(cell_rollup(areas, union(by_build), load_signoffs()), len(by_build)))
    body = '\n'.join(parts)
    if not COVERAGE_TXT.is_file():
        COVERAGE_TXT.write_text(
            'COVERAGE — radial focus + generated per-cell table\n'
            f'{BEGIN}\n{body}\n{END}\n'
        )
    else:
        text = COVERAGE_TXT.read_text()
        if BEGIN not in text or END not in text:
            COVERAGE_TXT.write_text(text.rstrip() + f'\n\n{BEGIN}\n{body}\n{END}\n')
        else:
            COVERAGE_TXT.write_text(replace_section(text, body))
    return body


def cmd_write(args) -> int:
    """Regenerate COVERAGE.txt from the registry (+ parcel areas when built).

    @param args: argparse namespace (unused)
    @returns: exit code
    """
    body = write_coverage()
    print(f'updated {COVERAGE_TXT.relative_to(ROOT)} ({body.count(chr(10)) + 1} lines)')
    return 0



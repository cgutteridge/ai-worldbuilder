def signoff_parcels(
    parcel_ids: list[str],
    build: str,
    *,
    note: str | None = None,
    date_str: str | None = None,
) -> tuple[list[str], list[tuple[str, str]]]:
    """Sign off parcels when touched 100%.

    @param parcel_ids: coverage parcel ids (unknown ids are refused)
    @param build: build (plan) name recorded in the cell journal
    @param note: optional note stored in COVERAGE-SIGNOFFS.jsonl
    @param date_str: ISO date (default today)
    @returns: (signed parcel ids, [(pid, reason), ...] for refusals)
    """
    areas = load_areas()
    by_build = touched_by_build()
    touched = union(by_build)
    today = date_str or date.today().isoformat()
    def check(a, p, build_name):
        cols = p['set']
        t = len(cols & touched)
        if t < p['n']:
            miss = sorted(cols - touched)
            return f'touched {t}/{p["n"]} ({pct(t, p["n"])}) — {len(miss)} untouched, e.g. {miss[:4]}'
        if build_name is not None:
            if build_name in REVERTED:
                return f'{build_name} was reverted (I-009)'
            if build_name not in by_build:
                return f'no recorded build {build_name} in the cell journal'
            if not by_build[build_name] & cols:
                return f'{build_name} touched none of its columns'
        return None

    signed: list[str] = []
    refused: list[tuple[str, str]] = []
    for pid in parcel_ids:
        a, p = _find_parcel(areas, pid)
        if p is None:
            refused.append((pid, 'no such parcel'))
            continue
        why = check(a, p, build)
        if why:
            refused.append((pid, why))
            continue
        append_signoff({
            'parcel': p['id'],
            'area': a.name,
            'build': build,
            'date': today,
            'columns': p['n'],
            'digest': p['digest'],
            'note': note,
        })
        signed.append(pid)
    if signed:
        write_coverage(areas, by_build)
    return signed, refused



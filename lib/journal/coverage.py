def scan_polygon(rings, bbox):
    """Columns whose centre lies inside a polygon, by even-odd scanline over all rings.

    Same inside test as osm_footprints._inside (holes are inner rings), but one pass per row
    so large umbrella polygons (the campus) stay cheap.

    @param rings: [[(x, z), ...], ...] outer ring first, then holes; MC float coords
    @param bbox: (x0, z0, x1, z1) inclusive clip
    @returns: iterator of (x, z)
    """
    x0, z0, x1, z1 = bbox
    edges = [(a, b) for r in rings for a, b in zip(r, r[1:] + r[:1]) if a[1] != b[1]]
    if not edges:
        return
    zs = [v for (_, az), (_, bz) in edges for v in (az, bz)]
    for z in range(max(z0, math.floor(min(zs))), min(z1, math.ceil(max(zs))) + 1):
        zc = z + 0.5
        xs = sorted(ax + (zc - az) * (bx - ax) / (bz - az)
                    for (ax, az), (bx, bz) in edges if (az > zc) != (bz > zc))
        for a, b in zip(xs[::2], xs[1::2]):
            for x in range(max(x0, math.ceil(a - 0.5)), min(x1, math.ceil(b - 0.5) - 1) + 1):
                yield x, z


def osm_ref(p: dict) -> str:
    """Stable map reference of a feature: 'w<way id>' or 'r<relation id>'.

    @param p: feature properties (polygon layers carry osm_way_id or osm_id; lines osm_id)
    @returns: e.g. 'w23456789'
    """
    if p.get('osm_way_id'):
        return 'w' + str(p['osm_way_id'])
    if p.get('highway') and p.get('osm_id') and 'z_order' in p:
        return 'w' + str(p['osm_id'])
    return 'r' + str(p.get('osm_id'))


def property_label(p: dict) -> str:
    """Human label of a building: '<addr:street> <number>', else its name, else its tag.

    @param p: building feature properties
    @returns: label string
    """
    num, street = _addr(p)
    if num or street:
        return f'{street or "?"} {num or ""}'.strip()
    return p.get('name') or f'building={p.get("building")} {osm_ref(p)}'


def polygon_centroid(rings) -> tuple[int, int]:
    """Column of an outer ring's area centroid (vertex mean for a degenerate ring).

    @param rings: polygon rings; the first is the outer ring
    @returns: ``(x, z)`` integer column
    """
    ring = rings[0]
    a = cx = cz = 0.0
    for (x0, z0), (x1, z1) in zip(ring, ring[1:] + ring[:1]):
        w = x0 * z1 - x1 * z0
        a += w
        cx += (x0 + x1) * w
        cz += (z0 + z1) * w
    if abs(a) < 1e-9:
        return math.floor(sum(x for x, _ in ring) / len(ring)), math.floor(sum(z for _, z in ring) / len(ring))
    return math.floor(cx / (3 * a)), math.floor(cz / (3 * a))


def area_classes(idx: OSMIndex, bbox, report: Counter | None = None) -> dict:
    """Land-use class of every column of ``bbox`` that a non-building polygon covers (#253).

    Use polygons (what the land is for): the smallest wins. Cover polygons (grass, flowerbed,
    natural cover) set the class only where no use polygon covers the column. A polygon whose tag
    value the table does not know claims nothing; it is counted in ``report`` as ``key=value``.
    Reads ``idx.areas`` (whole polygons, even with no vertex in ``bbox``), never ``load_osm``.

    @param idx: OSMIndex
    @param bbox: inclusive ``(x0, z0, x1, z1)`` grid
    @param report: optional Counter that receives unlisted ``key=value`` counts
    @returns: ``{(x, z): (class, ref, 'use' | 'cover')}``
    """
    merged = {}
    for rings, p in idx.areas:
        hit = land_use.area_class(osm_tags(p))
        if hit is None:
            continue
        ref = osm_ref(p)
        if hit['kind'] is None:
            if report is not None:
                report[hit['value']] += 1
            continue
        m = merged.setdefault(ref, [hit, set()])
        m[1].update(scan_polygon(rings, bbox))
    out = {}
    cover = {}
    for ref, (hit, cells) in sorted(merged.items(), key=lambda kv: (len(kv[1][1]), kv[0])):
        target = out if hit['kind'] == 'use' else cover
        for c in cells:
            target.setdefault(c, (hit['class'], ref, hit['kind']))
    for c, v in cover.items():
        out.setdefault(c, v)
    return out


def _smallest_use_polygon(idx: OSMIndex, x: int, z: int) -> tuple | None:
    """Use class and reference at a column, ranked by whole polygon area."""
    sizes = Counter()
    hits = {}
    seen = set()
    for rings, props in idx.areas:
        hit = land_use.area_class(osm_tags(props))
        if hit is None or hit['kind'] != 'use':
            continue
        ref = osm_ref(props)
        key = (ref, tuple(tuple(tuple(point) for point in ring) for ring in rings))
        if key in seen:
            continue
        seen.add(key)
        ring_areas = [abs(sum(ax * bz - bx * az
                              for (ax, az), (bx, bz) in zip(ring, ring[1:] + ring[:1]))) / 2
                      for ring in rings]
        # OSMIndex stores the parts of a multipolygon separately under one reference.
        sizes[ref] += ring_areas[0] - sum(ring_areas[1:])
        if next(scan_polygon(rings, (x, z, x, z)), None) is not None:
            hits[ref] = hit['class']
    if not hits:
        return None
    ref = min(hits, key=lambda ref: (sizes[ref], ref))
    return hits[ref], ref


def building_land_use(idx: OSMIndex, rings, props: dict, classes: dict | None = None) -> dict:
    """Class of one building: own tags, else smallest use polygon at its centroid, else house number.

    @param idx: OSMIndex (for the checked extent)
    @param rings: building polygon rings
    @param props: building feature properties
    @param classes: result of :func:`area_classes`; omit to test the centroid directly
        against whole use polygons without rasterising their areas
    @returns: ``{'class', 'reason', 'ref'}``
    """
    cx, cz = polygon_centroid(rings)
    if classes is None:
        polygon = _smallest_use_polygon(idx, cx, cz)
    else:
        hit = classes.get((cx, cz))
        polygon = (hit[0], hit[1]) if hit and hit[2] == 'use' else None
    return land_use.classify_building(osm_tags(props), polygon=polygon,
                                      checked=idx.layer_covered('landuse', cx, cz), ref=osm_ref(props))


# Builds whose work was undone (I-009: façade shells on the pavement, reverted by
# broadlands_facade_revert + region snap I-009-revert).
REVERTED = frozenset({
    'portswood_x_broadlands_terrace_facade_1', 'portswood_x_broadlands_terrace_facade_1b',
    'portswood_x_broadlands_terrace_facade_2', 'portswood_x_broadlands_terrace_facade_2b',
    'portswood_x_broadlands_terrace_facade_2c', 'broadlands_facade_revert',
})
TOUCH_PASSES = ('feature', 'ground', 'trees', 'decor', 'other')


def touch_excluded(name: str) -> bool:
    """Whether a build's columns are omitted from touched-column evidence.

    @param name: plan name
    @returns: True if the build should not count as touched ground
    """
    return name in REVERTED or name.startswith('cell_marker_')


def touched_by_build(exclude=REVERTED) -> dict:
    """Columns covered by each build's latest recorded plan in the cell journal.

    Ghost massing does not count as touched ground.

    @param exclude: build names to ignore (default: REVERTED); also skips cell_marker_*
    @returns: {build name: set of (x, z)}
    """
    from cell_registry import view_registry
    return {name: cols for name, cols in view_registry().touched(TOUCH_PASSES).items()
            if name not in exclude and not touch_excluded(name)}


def load_holds() -> dict:
    """Open holds per cell from the cell journal ``hold`` notes (ticket #31).

    @returns: {(tx, tz): {id: record}}
    """
    from cell_registry import view_registry
    return {cell: {'registry': {'cell': list(cell), 'id': 'registry', 'reason': v.hold}}
            for cell, v in view_registry().view().items() if v.hold}


def focus_cell() -> tuple[int, int]:
    """Focus cell from the registry marker, else world-frame origin (ticket #31).

    @returns: (tx, tz)
    """
    from cell_registry import view_registry
    cur = view_registry().marker_cell()
    if cur is not None:
        return cur
    try:
        from cellmath import home_cell
        return home_cell()
    except Exception:
        pass
    if COVERAGE_TXT.exists():
        m = re.search(
            r'Origin cell for current focus:\s*tx=(-?\d+)\s+tz=(-?\d+)',
            COVERAGE_TXT.read_text(),
        )
        if m:
            return int(m.group(1)), int(m.group(2))
    raise SystemExit('no registry marker, home cell, or COVERAGE.txt focus line')


def registry_rollup_rows() -> list[dict]:
    """Per-cell status from the cell registry alone (ticket #33).

    @returns: [{'cell', 'r', 'status', 'left', 'ground', 'trees', 'decor', 'hold'}, ...]
              sorted by ring then cell; empty when the registry is empty
    """
    from cell_registry import view_registry

    try:
        fx, fz = focus_cell()
    except SystemExit:
        fx, fz = 0, 0
    rows = []
    for (tx, tz), v in view_registry().view().items():
        if v.hold:
            status = 'held'
        elif v.done:
            status = 'done'
        elif v.ground != 'none' or v.trees or v.decor:
            status = 'partial'
        else:
            status = 'registered'
        rows.append({
            'cell': (tx, tz),
            'r': max(abs(tx - fx), abs(tz - fz)),
            'status': status,
            'left': list(v.left),
            'ground': v.ground,
            'trees': v.trees,
            'decor': v.decor,
            'hold': v.hold,
            'marker': 'up' if v.marker else 'none',
        })
    return sorted(rows, key=lambda r: (r['r'], r['cell']))


def registry_rollup_text(rows: list[dict] | None = None) -> str:
    """Render registry cells for the COVERAGE.txt generated block.

    @param rows: from :func:`registry_rollup_rows` (default: compute)
    @returns: text lines (no markers)
    """
    rows = rows if rows is not None else registry_rollup_rows()
    lines = [
        f'registry rollup {datetime.now().strftime("%Y-%m-%d %H:%M")} '
        f'({len(rows)} cell(s); source = registry/journal.jsonl)',
        'tx,tz  |  r  |  status  |  ground  |  trees  |  decor  |  marker  |  left',
    ]
    if not rows:
        lines.append('(registry empty)')
        return '\n'.join(lines)
    for r in rows:
        tx, tz = r['cell']
        left = ', '.join(r['left']) if r['left'] else '—'
        hold = f' hold={r["hold"]}' if r.get('hold') else ''
        lines.append(
            f'{tx},{tz}  |  r={r["r"]}  |  status={r["status"]}{hold}  |  '
            f'ground={r["ground"]}  |  trees={"yes" if r["trees"] else "no"}  |  '
            f'decor={"yes" if r["decor"] else "no"}  |  marker={r["marker"]}  |  {left}'
        )
    return '\n'.join(lines)


def replace_section(text: str, body: str) -> str:
    """Swap the text between the BEGIN / END markers.

    @param text: whole COVERAGE.txt
    @param body: new generated block
    @returns: updated text
    @raises ValueError: if the markers are missing or out of order
    """
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise ValueError('COVERAGE.txt: generated markers missing or out of order')
    return text[:i + len(BEGIN)] + '\n' + body + '\n' + text[j:]


def write_coverage() -> str:
    """Refresh the registry rollup without replacing handwritten coverage notes.

    @returns: the generated block
    """
    body = registry_rollup_text()
    COVERAGE_TXT.parent.mkdir(parents=True, exist_ok=True)
    if not COVERAGE_TXT.is_file():
        COVERAGE_TXT.write_text(
            'COVERAGE — generated registry rollup\n'
            f'{BEGIN}\n{body}\n{END}\n'
        )
    else:
        text = COVERAGE_TXT.read_text()
        if BEGIN not in text or END not in text:
            COVERAGE_TXT.write_text(text.rstrip() + f'\n\n{BEGIN}\n{body}\n{END}\n')
        else:
            COVERAGE_TXT.write_text(replace_section(text, body))
    return body


def cmd_write(args) -> int:
    """Refresh COVERAGE.txt from the registry.

    @param args: argparse namespace (unused)
    @returns: exit code
    """
    write_coverage()
    print(f'updated {COVERAGE_TXT.relative_to(ROOT)}')
    return 0


def cmd_status(args) -> int:
    """Print registry status and holds, optionally for one cell.

    @param args: argparse namespace with cell and write
    @returns: exit code
    """
    rows = registry_rollup_rows()
    if args.cell is not None:
        rows = [r for r in rows if r['cell'] == args.cell]
    print(registry_rollup_text(rows))
    if args.write:
        write_coverage()
    return 0


def main() -> int:
    """CLI entry point for registry coverage views.

    @returns: exit code
    """
    ap = argparse.ArgumentParser(
        description='Registry coverage status and generated rollup.',
        epilog=COVERAGE_CHEATSHEET,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = ap.add_subparsers(dest='cmd', required=True)
    status = sub.add_parser('status', help='show registry cell/layer status and holds')
    status.add_argument('--cell', type=parse_cell, help='tx,tz: one registry cell')
    status.add_argument('--write', action='store_true', help='also refresh COVERAGE.txt')
    sub.add_parser('write', help='refresh COVERAGE.txt from the registry')
    args = ap.parse_args()
    return {'status': cmd_status, 'write': cmd_write}[args.cmd](args)


if __name__ == '__main__':
    sys.exit(main())
